"""AC-1: frozen expected-value tables for all five ecosystems, checked through `check`.

npm  : node-semver 7.8.6 (tests/data/npm_cases.json, generated by tools/refgen/gen_npm.js)
pypi : packaging 26.3 contains() = membership policy, packaging 24.2 contains() = install policy
cargo, composer, maven: hand-derived from official docs, one source URL per case
"""
from __future__ import annotations

import pytest

from conftest import load_data

NPM = load_data("npm_cases.json")
PYPI = load_data("pypi_cases.json")
CARGO = load_data("cargo_cases.json")["cases"]
COMPOSER = load_data("composer_cases.json")["cases"]
MAVEN = load_data("maven_cases.json")


def _npm_pairs():
    return [(r, v, v in hits) for r, hits in NPM["satisfies"].items() for v in NPM["versions"]]


def _pypi_pairs(policy: str):
    return [(r, v, v in hits) for r, hits in PYPI[policy].items() for v in PYPI["versions"]]


def test_each_ecosystem_has_at_least_30_cases():
    counts = {"npm": len(_npm_pairs()), "pypi": len(_pypi_pairs("membership")), "cargo": len(CARGO),
              "composer": len(COMPOSER), "maven": len(MAVEN["cases"])}
    assert all(n >= 30 for n in counts.values()), counts


def test_table_sources_are_recorded():
    assert NPM["source"] == "node-semver 7.8.6"
    assert PYPI["sources"] == {"membership": "packaging 26.3", "install": "packaging 24.2"}
    for case in CARGO + COMPOSER + MAVEN["cases"]:
        assert case["source"].startswith("https://")


def test_npm_matches_node_semver(rw):
    wrong = [(r, v, want) for r, v, want in _npm_pairs()
             if rw.cmd_check("npm", r, v, rw.Options())[0]["matches"] != want]
    assert not wrong, wrong[:5]


def test_npm_include_prerelease_matches_node_semver(rw):
    opts = rw.Options(include_prerelease=True)
    wrong = [(r, v) for r, hits in NPM["include_prerelease"].items() for v in NPM["versions"]
             if rw.cmd_check("npm", r, v, opts)[0]["matches"] != (v in hits)]
    assert not wrong, wrong[:5]


@pytest.mark.parametrize("policy", ["membership", "install"])
def test_pypi_matches_packaging(rw, policy):
    opts = rw.Options(pre_policy=policy)
    wrong = [(r, v, want) for r, v, want in _pypi_pairs(policy)
             if rw.cmd_check("pypi", r, v, opts)[0]["matches"] != want]
    assert not wrong, wrong[:5]


def test_pypi_policies_really_differ_in_the_tables():
    differing = [r for r in PYPI["membership"] if PYPI["membership"][r] != PYPI["install"][r]]
    assert len(differing) >= 10  # the 24.2 -> 26 behaviour change is part of what we freeze


def test_cargo_matches_docs(rw):
    wrong = [(c["range"], c["version"]) for c in CARGO
             if rw.cmd_check("cargo", c["range"], c["version"], rw.Options())[0]["matches"] != c["expected"]]
    assert not wrong, wrong


def test_composer_matches_docs(rw):
    wrong = []
    for c in COMPOSER:
        opts = rw.Options(minimum_stability=c["minimum_stability"])
        if rw.cmd_check("composer", c["range"], c["version"], opts)[0]["matches"] != c["expected"]:
            wrong.append((c["range"], c["version"], c["minimum_stability"]))
    assert not wrong, wrong


def test_maven_matches_docs(rw):
    wrong = [(c["range"], c["version"]) for c in MAVEN["cases"]
             if rw.cmd_check("maven", c["range"], c["version"], rw.Options())[0]["matches"] != c["expected"]]
    assert not wrong, wrong


def test_maven_version_order_specification(rw):
    parse = rw.MavenVer.parse
    for chain in MAVEN["order_chains"]:
        for lower, higher in zip(chain, chain[1:]):
            assert parse(lower) < parse(higher), (lower, higher)
    for group in MAVEN["equal_groups"]:
        for item in group:
            assert parse(item) == parse(group[0]), (item, group[0])


def test_probe_cases_from_research_are_covered(rw):
    """The 68 cases of the research probe: the headline ones are asserted by name."""
    check = lambda eco, r, v, **o: rw.cmd_check(eco, r, v, rw.Options(**o))[0]["matches"]  # noqa: E731
    assert check("npm", "^0.0", "0.1.0") is False
    assert check("npm", ">=0.9.0", "0.9.1-build.4") is False
    assert check("npm", "*", "1.0.0-rc.1") is False
    assert check("composer", "~1.2", "1.9.0") is True
    assert check("cargo", "0.2.3", "0.3.0") is False
    assert check("pypi", "~=1.4", "2.0") is False
    assert check("pypi", ">1.5", "1.5.post1") is False
    assert check("maven", "[1.0,2.0)", "2.0-rc1") is True
